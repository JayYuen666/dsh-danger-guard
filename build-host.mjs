#!/usr/bin/env node
/// <reference types="node" />
// 构建 host 产物（host.js + settings.js）：rolldown 把入口及其 `./lib/*` 依赖各自打成
// 单文件 ESM，落在**包根**（与源码同目录，故 `import.meta.dirname` 的语义与源码态完全一致）。
// 为什么必须有这一步：Node 对 node_modules 里的 .ts 直接抛
// ERR_UNSUPPORTED_NODE_MODULES_TYPE_STRIPPING（实测），而发布出去的包正是躺在
// node_modules 里被 dsh 载入的；官方示例包（docs/user/develop/basic/publish.zh.md
// 的 hello-plugin）也是包根放 index.js 产物。本仓 host.ts + client.js 同形态。
// 不产 .d.ts：插件包对外没有 TS API——dsh 按包名载入运行，没有人 import 它。
// 顶部 node reference：oxlint 类型检查对 .mjs 不自动加载 @types/node，需显式声明
// 才能解析 node:fs/promises、process、import.meta（否则整文件按 error 类型误报 unsafe）。
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { rolldown } from "rolldown";
import { rolldownDecorators } from "./decorator-transform.mjs";
import { canonicalizeRegionPaths } from "@jayyuen66/dsh-plugin-shared/lib/canonicalize-region-paths";

const root = import.meta.dirname;

/** @type {unknown} */
const pkgJson = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));

/**
 * 从 JSON.parse 的 unknown 投影为 Record（非对象 → 空对象兜底），避免 any 索引。
 * @param {unknown} raw
 * @returns {Record<string, unknown>}
 */
function asRecord(raw) {
  if (raw !== null && typeof raw === "object" && !Array.isArray(raw)) {
    return raw;
  }
  return {};
}

/**
 * 取依赖表里的包名清单（值即外部化说明符）。
 * @param {string} field
 * @returns {string[]}
 */
function dependencyNames(field) {
  const table = asRecord(asRecord(pkgJson)[field]);
  return Object.keys(table).filter((name) => typeof table[name] === "string");
}

// dependencies/peerDependencies 一律外部化：它们由 pnpm 真实安装，产物里保留裸
// 说明符才拿得到单例（内联会把 shared 的模块级状态复制成多份）。子路径说明符同样
// 要外部化——external 的字符串项是精确匹配，所以按「包名段」判定而不是枚举子路径。
const externalNames = new Set([
  ...dependencyNames("dependencies"),
  ...dependencyNames("peerDependencies"),
]);

/**
 * 说明符的包名段：`@scope/pkg/sub` → `@scope/pkg`，`pkg/sub` → `pkg`。
 * @param {string} id
 * @returns {string}
 */
function packageNameOf(id) {
  const segments = id.split("/");
  if (id.startsWith("@")) {
    return segments.slice(0, 2).join("/");
  }
  return segments[0] ?? id;
}

/**
 * rolldown 外部化判据。
 * @param {string} id
 * @returns {boolean}
 */
const isExternal = (id) => externalNames.has(packageNameOf(id));

/**
 * 生成一个 host 产物：完整文本 + **打进 chunk 的模块 id 清单**。
 * @param {string} inputFile 包根下的入口文件名
 * @returns {Promise<{code: string, inlinedModules: string[]}>}
 */
async function buildEntry(inputFile) {
  const bundle = await rolldown({
    input: path.join(root, inputFile),
    external: isExternal,
    platform: "node",
    resolve: { extensions: [".ts", ".mjs", ".js"] },
    // 装饰器预转换（为什么必须有：见 decorator-transform.mjs 的文件头）。
    plugins: [rolldownDecorators()],
  });
  // `minify: true`：产物是给 dsh 装载器 `await import()` 的（vendor/include/src/index.ts:222），
  // 文本形态不影响装载，而注释与空白占掉的字节是**真实装载成本**（浏览器侧那枚按平台计账）。
  // 实测 host 309,394→86,727 B、settings 7,293→2,881 B、client 38,782→23,436 B；types/ 的
  // 声明**不**压缩：那是发布面给编辑器读的 API 文档（JSDoc 就是它的正文）。
  // ⚠ 副作用两处：
  //   ① `//#region` 标记在 minify 下**不再出现**（实测），所以下面那次 region 折算现在是空操作
  //      —— 留着它是**故意的**：它压的是"`process.cwd()` 泄漏进产物"这条性质，rolldown 一旦
  //      恢复 region 标记就立刻重新需要，而留在那里不花任何字节。
  //   ② 内联体的**函数名会被 mangle**（实测：故意不外部化 dsh-brand 时，产物里 `brandNumber`
  //      一次都查不到）⇒ 任何"某函数体没被内联"的**文本**判据都会变成恒绿。跨包外部化的门禁
  //      因此改走**结构性判据**：下面把 chunk 的内联模块 id 一并交出去（buildHostReport），
  //      由用例对着 package.json 的依赖表判"一个都没进来"。
  // `comments: false` 与 minify 一起给：minifier 会把**看起来像注解的注释**留下（实测我们源码里
  // `lib/tool-ledger.ts` 那两处 `v8 ignore` 提示原样进了产物）—— 而产物里没有任何人在量覆盖率，
  // 那几个字节与那点误导都不值得发出去（`.probe` 实测这一档再省下几百字节）。
  const { output } = await bundle.generate({ format: "esm", minify: true, comments: false });
  const chunk = output.find((item) => item.type === "chunk");
  if (chunk === undefined) {
    throw new Error(`rolldown generate returned no chunk output for ${inputFile}`);
  }
  // `//#region` 行的路径由 rolldown 按 process.cwd() 算出 ⇒ 同一份源码有两种字节（cwd=包根 写
  // `lib/x.ts`，cwd=plugins/ 写 `<包名>/lib/x.ts`）。折成 canonical 必须落在**返回值之前**：
  // test/host-freshness.ts 拿内存构建与磁盘产物逐字节比（host.js 与 settings.js 各一趟），
  // 只在一侧折就永远红。
  const code = canonicalizeRegionPaths(chunk.code.trimEnd(), root);
  return {
    code: `// GENERATED by build-host.mjs — edit ${inputFile} / lib/*.ts, then run \`node build-host.mjs\`.\n${code}\n`,
    // 本包源码模块一律是**绝对路径**；外部依赖（external）根本不出现在这里 —— 那正是判据：
    // 依赖表里的包名一旦出现在这张清单里，就是有人把它从 external 名单里挪走了（内联）。
    inlinedModules: chunk.moduleIds,
  };
}

/**
 * 生成 host.js 的完整文本（拦截半）。
 * @returns {Promise<string>}
 */
export async function buildHost() {
  const { code } = await buildEntry("host.ts");
  return code;
}

/** host.ts 的**产物 + 内联模块清单**（跨包外部化那道结构性门禁走它，见 buildEntry 的说明）。
 *  @returns {Promise<{code: string, inlinedModules: string[]}>} */
export async function buildHostReport() {
  return buildEntry("host.ts");
}

/**
 * 生成 settings.js 的完整文本（设置半 / bulkhead 条目）。
 * 单独一次 rollup 构建而不是同一次多输入：多输入会把 lib/settings-schema.ts 提成
 * 共享 chunk 并改写产物间的相对说明符，本包要的是**两个自包含单文件**（与 host.js 同形）。
 * @returns {Promise<string>}
 */
export async function buildSettings() {
  const { code } = await buildEntry("settings-host.ts");
  return code;
}

/** settings-host.ts 的产物 + 内联模块清单（同 buildHostReport）。
 *  @returns {Promise<{code: string, inlinedModules: string[]}>} */
export async function buildSettingsReport() {
  return buildEntry("settings-host.ts");
}

/**
 * 落盘一个 host 产物。
 * @param {string} file 包根下的产物文件名
 * @param {string} out 产物文本
 * @returns {Promise<void>}
 */
async function writeArtifact(file, out) {
  await writeFile(path.join(root, file), out, "utf8");
  console.info(`${file} written:`, out.length, "chars");
}

async function main() {
  // 两个条目各跑一次构建（不是同一次多输入）：并发只是省一次冷启动，产物互不共享 chunk。
  const [host, settings] = await Promise.all([buildHost(), buildSettings()]);
  await writeArtifact("host.js", host);
  await writeArtifact("settings.js", settings);
}

if (process.argv[1] === import.meta.filename) {
  try {
    await main();
  } catch (error) {
    console.error(error);
    process.exitCode = 1;
  }
}
